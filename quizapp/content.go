type block struct {
	code bool
	text string
}

type question struct {
	prompt  string
	stem    string
	why     string
	choices []string
	answer  int
	code    string
	accept  [][]string
}

type day struct {
	title     string
	lesson    []block
	questions []question
}

func p(s string) block    { return block{text: s} }
func code(s string) block { return block{code: true, text: s} }

func choice(prompt, why string, answer int, choices ...string) question {
	return question{prompt: prompt, why: why, choices: choices, answer: answer}
}

func choiceCode(prompt, stem, why string, answer int, choices ...string) question {
	return question{prompt: prompt, stem: stem, why: why, choices: choices, answer: answer}
}

func fill(prompt, why, code string, blanks ...[]string) question {
	return question{prompt: prompt, why: why, code: code, accept: blanks}
}

